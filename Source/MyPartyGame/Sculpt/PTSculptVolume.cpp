// ─── Constructor ─────────────────────────────────────────────────────────────

APTSculptVolume::APTSculptVolume()
{
    PrimaryActorTick.bCanEverTick = true;
    Mesh = CreateDefaultSubobject<UProceduralMeshComponent>(TEXT("Mesh"));
    SetRootComponent(Mesh);
    Mesh->bUseAsyncCooking = true;
}

void APTSculptVolume::BeginPlay()
{
    Super::BeginPlay();
    InitGrid();
    RebuildMesh();
}

void APTSculptVolume::Tick(float DeltaTime)
{
    Super::Tick(DeltaTime);
    if (!bDirty) return;
    TimeSinceRebuild += DeltaTime;
    if (TimeSinceRebuild >= RebuildInterval)
    {
        TimeSinceRebuild = 0.f;
        bDirty = false;
        RebuildMesh();
    }
}

// ─── Grid helpers ─────────────────────────────────────────────────────────────

void APTSculptVolume::InitGrid()
{
    Grid.SetNum(GridSize * GridSize * GridSize);
    for (int32 z = 0; z < GridSize; ++z)
        for (int32 y = 0; y < GridSize; ++y)
            for (int32 x = 0; x < GridSize; ++x)
                // Flat slab: bottom 5 layers are solid
                Grid[Idx(x, y, z)] = (z < 5) ? 1.f : -1.f;
}

bool APTSculptVolume::InBounds(int32 X, int32 Y, int32 Z) const
{
    return X >= 0 && X < GridSize && Y >= 0 && Y < GridSize && Z >= 0 && Z < GridSize;
}

int32 APTSculptVolume::Idx(int32 X, int32 Y, int32 Z) const
{
    return X + Y * GridSize + Z * GridSize * GridSize;
}

float APTSculptVolume::GetVal(int32 X, int32 Y, int32 Z) const
{
    return InBounds(X, Y, Z) ? Grid[Idx(X, Y, Z)] : -1.f;
}

void APTSculptVolume::SetVal(int32 X, int32 Y, int32 Z, float V)
{
    if (InBounds(X, Y, Z))
        Grid[Idx(X, Y, Z)] = FMath::Clamp(V, -1.f, 1.f);
}

FVector APTSculptVolume::WorldToGrid(FVector W) const
{
    FVector Local = GetActorTransform().InverseTransformPosition(W);
    return Local / VoxelSize;
}

FVector APTSculptVolume::GridToLocal(float X, float Y, float Z) const
{
    return FVector(X, Y, Z) * VoxelSize;
}

float APTSculptVolume::SampleDensity(float X, float Y, float Z) const
{
    int32 x0 = FMath::FloorToInt(X), y0 = FMath::FloorToInt(Y), z0 = FMath::FloorToInt(Z);
    float fx = X - x0, fy = Y - y0, fz = Z - z0;
    auto G = [&](int32 xi, int32 yi, int32 zi) { return GetVal(xi, yi, zi); };
    return FMath::Lerp(
        FMath::Lerp(FMath::Lerp(G(x0,y0,z0),   G(x0+1,y0,z0),   fx),
                    FMath::Lerp(G(x0,y0+1,z0),  G(x0+1,y0+1,z0), fx), fy),
        FMath::Lerp(FMath::Lerp(G(x0,y0,z0+1),  G(x0+1,y0,z0+1),  fx),
                    FMath::Lerp(G(x0,y0+1,z0+1), G(x0+1,y0+1,z0+1),fx), fy),
        fz);
}

FVector APTSculptVolume::SampleGradient(float X, float Y, float Z) const
{
    const float d = 0.5f;
    FVector Grad(
        SampleDensity(X+d,Y,Z) - SampleDensity(X-d,Y,Z),
        SampleDensity(X,Y+d,Z) - SampleDensity(X,Y-d,Z),
        SampleDensity(X,Y,Z+d) - SampleDensity(X,Y,Z-d)
    );
    // Negate: gradient points into material, normal must point out.
    return (-Grad).GetSafeNormal();
}

// ─── Brush operations ─────────────────────────────────────────────────────────

void APTSculptVolume::ApplyBrush(FVector WorldPos, EPTBrushMode Mode, float Radius, float Strength, float DeltaTime)
{
    FVector GridCenter = WorldToGrid(WorldPos);
    int32 R = FMath::CeilToInt(Radius / VoxelSize) + 1;

    int32 x0 = FMath::Max(0, FMath::FloorToInt(GridCenter.X) - R);
    int32 x1 = FMath::Min(GridSize - 1, FMath::CeilToInt(GridCenter.X) + R);
    int32 y0 = FMath::Max(0, FMath::FloorToInt(GridCenter.Y) - R);
    int32 y1 = FMath::Min(GridSize - 1, FMath::CeilToInt(GridCenter.Y) + R);
    int32 z0 = FMath::Max(0, FMath::FloorToInt(GridCenter.Z) - R);
    int32 z1 = FMath::Min(GridSize - 1, FMath::CeilToInt(GridCenter.Z) + R);

    const float RadiusGrid = Radius / VoxelSize;

    if (Mode == EPTBrushMode::Smooth)
    {
        // Smooth: average with neighbors weighted by falloff. Two-pass to avoid order dependency.
        TArray<float> NewVals;
        NewVals.SetNum((x1-x0+1) * (y1-y0+1) * (z1-z0+1));
        int32 wi = 0;
        for (int32 z = z0; z <= z1; ++z)
        for (int32 y = y0; y <= y1; ++y)
        for (int32 x = x0; x <= x1; ++x, ++wi)
        {
            float dist = FVector::Dist(GridCenter, FVector(x,y,z));
            if (dist > RadiusGrid) { NewVals[wi] = GetVal(x,y,z); continue; }
            float falloff = 1.f - dist / RadiusGrid;
            float avg = 0.f;
            int32 cnt = 0;
            for (int32 dz = -1; dz <= 1; ++dz)
            for (int32 dy = -1; dy <= 1; ++dy)
            for (int32 dx = -1; dx <= 1; ++dx)
            {
                avg += GetVal(x+dx, y+dy, z+dz);
                ++cnt;
            }
            avg /= cnt;
            NewVals[wi] = FMath::Lerp(GetVal(x,y,z), avg, falloff * Strength * DeltaTime * 5.f);
        }
        wi = 0;
        for (int32 z = z0; z <= z1; ++z)
        for (int32 y = y0; y <= y1; ++y)
        for (int32 x = x0; x <= x1; ++x, ++wi)
            SetVal(x, y, z, NewVals[wi]);
    }
    else
    {
        for (int32 z = z0; z <= z1; ++z)
        for (int32 y = y0; y <= y1; ++y)
        for (int32 x = x0; x <= x1; ++x)
        {
            float dist = FVector::Dist(GridCenter, FVector(x,y,z));
            if (dist > RadiusGrid) continue;
            float falloff = 1.f - dist / RadiusGrid;
            float delta   = Strength * falloff * DeltaTime;
            float cur     = GetVal(x, y, z);
            SetVal(x, y, z, cur + (Mode == EPTBrushMode::Add ? delta : -delta));
        }
    }

    bDirty = true;
}

// ─── Marching Cubes ───────────────────────────────────────────────────────────

FVector APTSculptVolume::Interp(FVector P1, FVector P2, float V1, float V2) const
{
    if (FMath::Abs(V1 - V2) < 1e-5f) return (P1 + P2) * 0.5f;
    float t = -V1 / (V2 - V1);
    return P1 + t * (P2 - P1);
}

FVector APTSculptVolume::InterpNormal(FVector P1, FVector P2, FVector G1, FVector G2, float V1, float V2) const
{
    if (FMath::Abs(V1 - V2) < 1e-5f) return (G1 + G2).GetSafeNormal();
    float t = -V1 / (V2 - V1);
    return (G1 + t * (G2 - G1)).GetSafeNormal();
}

void APTSculptVolume::RunMarchingCubes(TArray<FVector>& OutVerts,
                                        TArray<int32>&   OutTris,
                                        TArray<FVector>& OutNormals)
{
    OutVerts.Reset();
    OutTris.Reset();
    OutNormals.Reset();

    // Corner offsets for the 8 corners of each cube cell
    static const int32 CX[8] = {0,1,1,0,0,1,1,0};
    static const int32 CY[8] = {0,0,1,1,0,0,1,1};
    static const int32 CZ[8] = {0,0,0,0,1,1,1,1};

    // Edge vertex pairs
    static const int32 EV0[12] = {0,1,2,3,4,5,6,7,0,1,2,3};
    static const int32 EV1[12] = {1,2,3,0,5,6,7,4,4,5,6,7};

    for (int32 z = 0; z < GridSize - 1; ++z)
    for (int32 y = 0; y < GridSize - 1; ++y)
    for (int32 x = 0; x < GridSize - 1; ++x)
    {
        float val[8];
        FVector pos[8], grad[8];
        int32 cubeIdx = 0;

        for (int32 c = 0; c < 8; ++c)
        {
            int32 cx = x + CX[c], cy = y + CY[c], cz = z + CZ[c];
            val[c]  = GetVal(cx, cy, cz);
            pos[c]  = GridToLocal((float)cx, (float)cy, (float)cz);
            grad[c] = SampleGradient((float)cx, (float)cy, (float)cz);
            if (val[c] > 0.f) cubeIdx |= (1 << c);
        }

        if (EdgeTable[cubeIdx] == 0) continue;

        FVector edgePos[12], edgeNorm[12];
        for (int32 e = 0; e < 12; ++e)
        {
            if (EdgeTable[cubeIdx] & (1 << e))
            {
                int32 a = EV0[e], b = EV1[e];
                edgePos[e]  = Interp(pos[a], pos[b], val[a], val[b]);
                edgeNorm[e] = InterpNormal(pos[a], pos[b], grad[a], grad[b], val[a], val[b]);
            }
        }

        for (int32 t = 0; TriTable[cubeIdx][t] != -1; t += 3)
        {
            int32 e0 = TriTable[cubeIdx][t+0];
            int32 e1 = TriTable[cubeIdx][t+1];
            int32 e2 = TriTable[cubeIdx][t+2];

            int32 base = OutVerts.Num();
            OutVerts.Add(edgePos[e0]);
            OutVerts.Add(edgePos[e1]);
            OutVerts.Add(edgePos[e2]);
            OutNormals.Add(edgeNorm[e0]);
            OutNormals.Add(edgeNorm[e1]);
            OutNormals.Add(edgeNorm[e2]);
            OutTris.Add(base);
            OutTris.Add(base + 1);
            OutTris.Add(base + 2);
        }
    }
}

void APTSculptVolume::RebuildMesh()
{
    TArray<FVector>   Verts, Normals;
    TArray<int32>     Tris;
    TArray<FVector2D> UVs;
    TArray<FColor>    Colors;
    TArray<FProcMeshTangent> Tangents;

    RunMarchingCubes(Verts, Tris, Normals);
    Mesh->CreateMeshSection(0, Verts, Tris, Normals, UVs, Colors, Tangents, /*bCreateCollision=*/true);

    UE_LOG(LogTemp, Log, TEXT("[PTSculptVolume] Mesh rebuilt: %d verts, %d tris"), Verts.Num(), Tris.Num() / 3);
}
